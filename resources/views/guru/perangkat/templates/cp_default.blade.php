    <h2 style="text-align: center;"><strong>CAPAIAN PEMBELAJARAN</strong><br><strong>MATA PELAJARAN AL-QUR'AN HADIS</strong></h2>
    <p>&nbsp;</p>
    <h4><strong>A. Rasional Mata Pelajaran Al-Qur'an Hadis</strong></h4>
    <p>Mata Pelajaran Al-Qur'an Hadis adalah sumber pokok ajaran Islam dan pedoman hidup kaum muslimin. Memahami dengan tepat dua warisan Rasulullah Saw., adalah syarat utama untuk memahami ajaran Islam. Tanpa pemahaman yang tepat terhadap Al-Qur'an dan Hadis, mustahil dapat mengamalkan ajaran Islam sesuai dengan makna yang terkandung di dalamnya.</p>
    <p>&nbsp;</p>
    <h4><strong>B. Tujuan Mata Pelajaran Al-Qur'an Hadis</strong></h4>
    <p>Secara substansial, mata pelajaran Al-Qur'an Hadis bertujuan memberikan motivasi kepada peserta didik untuk mencintai kitab sucinya, mempelajari, dan mempraktikkan ajaran dan nilai-nilai yang terkandung dalam Al-Qur'an dan Hadis sebagai sumber utama ajaran Islam dan sekaligus menjadi pegangan hidup dalam kehidupan sehari-hari.</p>
    <ol>
        <li>Meningkatkan kecintaan peserta didik terhadap Al-Qur'an dan Hadis;</li>
        <li>Membimbing peserta didik agar mampu membaca, menerjemahkan, menganalisis kandungan ayat-ayat Al-Qur'an dan Hadis;</li>
        <li>Membekali peserta didik dengan dalil-dalil yang terdapat dalam Al-Qur'an dan Hadis sebagai pedoman dalam kehidupan dan solusi dalam mennyelesaikan segala permasalahannya;</li>
    </ol>
    <p>&nbsp;</p>
    <h4><strong>C. Karakteristik Mata Pelajaran Al-Qur'an Hadis</strong></h4>
    <p>Mata pelajaran Al-Qur'an Hadis merupakan mata pelajaran yang memuat pedoman dasar ajaran agama Islam, yakni Al-Qur'an dan Sunnah Nabi Muhammad saw. (Hadis). Al-Qur'an Hadis sebagai sebuah mata pelajaran menekankan kemampuan baca tulis yang baik dan benar, memahami makna secara tekstual dan kontekstual, serta mengamalkan kandungannya dalam kehidupan sehari-hari.</p>
    <p>&nbsp;</p>
